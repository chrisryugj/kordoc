/**
 * 첨자 행 — 본문 줄 위에 뜬 작은 첨자가 한 줄에 넷("(’10)10.2만건 → (’25)17.1만건")이면 아이템 수 상한(셋)에 걸려 따로 행이 됐다.
 * 넓은 간격의 넷 칸 행이 열 앵커가 되어 보도자료 본문 쪽이 통째로 4열 표가 되고(클러스터 감지), 문단에서는 첨자만 모은 줄이
 * 본문 줄 앞에 따로 나왔다. 아이템마다 옆 줄 글자 앞뒤에 붙은 짧은 첨자면 개수와 상관없이 본문 줄에 흡수한다
 * (cluster-detector mergeOverlappingRows · text-line mergeSuperscriptLines).
 */

import { describe, it } from "node:test"
import assert from "node:assert/strict"
import { detectClusterTables, type ClusterItem } from "../src/pdf/cluster-detector.js"
import { extractPageBlocksFallback } from "../src/pdf/page-blocks.js"
import type { NormItem } from "../src/pdf/text-line.js"

type Row = [y: number, fontSize: number, items: Array<[text: string, x: number, w: number]>]
// 여성경제활동지원센터 공모전 보도자료 2쪽 (pdf.js 좌표, 연도 위첨자 7.7pt · 본문 12pt)
const SUP_10: Row = [442, 8, [["(’10)", 158, 15], ["(‘25)", 240, 15], ["(’10)", 368, 15], ["(‘25)", 445, 15]]]
const LINE_10: Row = [437, 12, [["*", 80, 5], ["취업", 91, 24], ["건수", 120, 24], [":", 149, 3], ["10.2", 172, 22], ["만건", 194, 24], ["→", 223, 11],
  ["17.1", 254, 22], ["만건", 276, 24], [",", 299, 3], ["구직건수", 308, 47], [":", 360, 3], ["16.4", 383, 22], ["만건", 405, 24], ["→", 428, 11],
  ["54.9", 459, 22], ["만건", 481, 24]]]
const SUP_14: Row = [423, 8, [["(’14)", 206, 15], ["(‘17)", 283, 15], ["(‘19)", 360, 15], ["(‘25)", 437, 15]]]
const LINE_14: Row = [418, 12, [["*", 80, 5], ["경력단절여성", 91, 71], ["규모", 168, 24], [":", 198, 3], ["2,164", 221, 28], ["천", 249, 12], ["→", 266, 11],
  ["1,811", 298, 28], ["천", 326, 12], ["→", 343, 11], ["1,699", 375, 28], ["천", 403, 12], ["→", 420, 11], ["1,105", 452, 28], ["천", 480, 12]]]
// 첫 첨자 뒤에는 빈칸 하나(0.475em)가 있다
const SUP_16: Row = [346, 8, [["(’10)", 208, 15], ["(‘16)", 306, 15], ["(‘26)", 407, 15]]]
const LINE_16: Row = [341, 12, [["*", 80, 5], ["과정수", 91, 36], ["(", 127, 4], ["고부가가치", 130, 59], [")", 190, 4], [":", 199, 3], ["184", 228, 19], ["개", 247, 12],
  ["(0", 259, 10], ["개", 269, 12], [")", 280, 4], ["→", 290, 11], ["690", 321, 20], ["개", 340, 12], ["(25", 352, 17], ["개", 369, 12], [")", 381, 4],
  ["→", 390, 11], ["795", 422, 20], ["개", 441, 12], ["(103", 453, 23], ["개", 476, 12], [")", 488, 4]]]
// 본문 줄이 이 쪽 다른 곳에 있는 첨자 행
const SUP_19: Row = [174, 8, [["’19", 196, 10], ["‘25", 276, 10], ["’19", 387, 10], ["‘25", 461, 10]]]
// 사면재해 대응체계 보도자료 1쪽 — 부처 첨자 다섯
const SUP_AGENCY: Row = [103.8, 7.7, [["행안부", 73.8, 22], ["국토부", 149.3, 22.1], ["농식품부", 236, 29.3], ["기후부", 296.1, 22.1], ["국가유산청", 455.5, 36.5]]]
const LINE_AGENCY: Row = [98.5, 12, [["*", 62.4, 5.1], ["급경사지", 95.3, 45.9], [",", 140.4, 2.7], ["도로비탈면", 170.9, 57.1], [",", 227.3, 2.6], ["농지", 264.8, 23.3],
  [",", 287.4, 2.6], ["발전시설", 317.7, 45.8], ["·", 362.8, 2.6], ["태양광", 365.3, 34.6], ["·", 399.1, 2.7], ["국립공원", 401.5, 45.9], [",", 446.6, 2.7],
  ["국가유산", 491.5, 45.1], [",", 535.6, 2.6]]]
// 재정운용전략협의회 모두발언 2쪽 — 원문자 첨자 열
const SUP_CIRCLED: Row = [312.3, 7.7, [["①", 107.5, 7.7], ["②", 179.3, 7.7], ["③", 217.1, 7.7], ["④", 255, 7.7], ["⑤", 292.9, 7.7], ["⑥", 330.7, 7.7],
  ["⑦", 379.9, 7.7], ["⑧", 417.8, 7.7], ["⑨", 455.6, 7.7], ["⑩", 493.6, 7.6]]]
const LINE_CIRCLED: Row = [307, 12, [["*", 94.9, 6.6], ["디스플레이", 114.7, 57.1], [",", 171.1, 2.6], ["항공", 186.5, 23.3], [",", 209, 2.7], ["물류", 224.3, 23.3],
  [",", 246.8, 2.7], ["유통", 262.2, 23.3], [",", 284.8, 2.6], ["조선", 300.1, 23.3], [",", 322.7, 2.6], ["자동차", 337.9, 34.6], [",", 371.8, 2.6],
  ["가전", 387.1, 23.3], [",", 409.7, 2.6], ["화학", 425, 23.3], [",", 447.6, 2.6], ["병원", 462.8, 23.3], [",", 485.4, 2.6], ["호텔", 500.8, 23.2]]]

const items = (...rows: Row[]): NormItem[] => rows.flatMap(([y, fontSize, its]) =>
  its.map(([text, x, w]) => ({ text, x, y, w, h: fontSize, fontSize, fontName: "F", isHidden: false })))

describe("첨자 행", () => {
  it("본문 줄 위 첨자 넷은 넓은 간격 행이 아니다 — 본문 쪽이 4열 표가 되지 않는다", () => {
    const cluster: ClusterItem[] = items(SUP_10, LINE_10, SUP_14, LINE_14, SUP_16, LINE_16, SUP_19)
    assert.deepEqual(detectClusterTables(cluster, 2).map(r => [r.table.rows, r.table.cols]), [])
  })

  it("한글 부처 첨자·원문자 첨자도 글자 앞에 붙는다", () => {
    assert.deepEqual(extractPageBlocksFallback(items(SUP_AGENCY, LINE_AGENCY), 1).map(b => b.text),
      ["* 행안부급경사지, 국토부도로비탈면, 농식품부농지, 기후부발전시설·태양광·국립공원, 국가유산청국가유산,"])
    assert.deepEqual(extractPageBlocksFallback(items(SUP_CIRCLED, LINE_CIRCLED), 2).map(b => b.text),
      ["* ①디스플레이, ②항공, ③물류, ④유통, ⑤조선, ⑥자동차, ⑦가전, ⑧화학, ⑨병원, ⑩호텔"])
  })

  it("라틴 글자·연산자 든 조각(적분 위끝 \"3a+x\")은 다음 글자 앞에 붙어 있어도 첨자 행으로 흡수하지 않는다", () => {
    const limits: Row = [106, 6, [["3a+x", 106, 14], ["2a+2", 166, 14], ["4a+1", 226, 14]]]
    const body: Row = [100, 10, [["∫", 100, 6], ["g(t)dt", 120, 30], ["=", 152, 6], ["∫", 160, 6], ["g(t)dt", 180, 30], ["+", 212, 6], ["∫", 220, 6], ["g(t)dt", 240, 30]]]
    assert.deepEqual(extractPageBlocksFallback(items(limits, body), 1).map(b => b.text), ["3a+x\t2a+2\t4a+1", "∫ g(t)dt = ∫ g(t)dt + ∫ g(t)dt"])
  })

  it("첨자는 본문 줄 제자리에 붙는다 (빈칸 하나 뒤 첨자 포함)", () => {
    const blocks = extractPageBlocksFallback(items(SUP_10, LINE_10, SUP_14, LINE_14, SUP_16, LINE_16), 2)
    assert.deepEqual(blocks.map(b => b.text), [
      "* 취업 건수 : (’10)10.2만건 → (‘25)17.1만건, 구직건수 : (’10)16.4만건→ (‘25)54.9만건",
      "* 경력단절여성 규모 : (’14)2,164천 → (‘17)1,811천 → (‘19)1,699천 → (‘25)1,105천",
      "* 과정수(고부가가치) : (’10) 184개(0개) → (‘16)690개(25개) → (‘26)795개(103개)",
    ])
  })
})
