  "(?:0\\d{1,2}[-)．. ]\\s?\\d{3,4}[-．. ]\\d{4}|\\+82|1[568]\\d\\d-\\d{4})"
/** 문맥어와 이름 사이 — 쌍점 또는 공백 (표 칸 경계는 라벨만: 역할어 칸 옆은 대개 하위 라벨 칸 "신고인 | 조합명") */
