/** 실측 폭표가 있는 글꼴인지 */
export function hasFontMetrics(face: string | null | undefined): boolean {
  return !!face && Object.prototype.hasOwnProperty.call(FONTS, face.trim())
}

/** 코드포인트 advance(em×1000). 폭표 없는 글꼴은 null — 호출부가 근사 클래스로 폴백 */
export function fontAdvanceEm1000(face: string, cp: number): number | null {
  if (!hasFontMetrics(face)) return null
  const m = FONTS[face.trim()]
  if (cp >= 0x20 && cp <= 0x7e) return m.ascii[cp - 0x20]
  return m.ex[cp] ?? (isHalfwidthForm(cp) ? 500 : m.han !== undefined && isHanja(cp) ? m.han : m.cjk)
}

/** CJK 통합 한자(확장 A·호환 포함) */
function isHanja(cp: number): boolean {
  return (cp >= 0x4e00 && cp <= 0x9fff) || (cp >= 0x3400 && cp <= 0x4dbf) || (cp >= 0xf900 && cp <= 0xfaff)
}

/** 문단 계산 전에 폭표를 한 번 선택한다 — 글자마다 글꼴명 trim·조회하지 않는다. */
export function fontWidthFn(face: string): ((cp: number) => number) | null {
  if (!hasFontMetrics(face)) return null
  const m = FONTS[face.trim()]
  // 표에 따로 없는 반각 형태(U+FF61~FFDC·FFE8~FFEE, ｢ ｣ ･ 등)는 반각 — 한컴 PDF 임베드 글꼴 실측 500
  return cp => cp >= 0x20 && cp <= 0x7e ? m.ascii[cp - 0x20] : m.ex[cp] ?? (isHalfwidthForm(cp) ? 500 : m.han !== undefined && isHanja(cp) ? m.han : m.cjk)
}

/** 유니코드 반각 형태 블록 */
export function isHalfwidthForm(cp: number): boolean {
  return (cp >= 0xff61 && cp <= 0xffdc) || (cp >= 0xffe8 && cp <= 0xffee)
}
